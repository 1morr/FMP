import 'package:fmp/legacy_import/legacy_snapshot.dart';

// 轉換器測試用的 `LegacySnapshot` 積木：只寫出關心的欄位，其餘給舊版的初值。全是編造資料。

/// 測試用的固定時間（本機時間，和 Isar 讀出來的一樣不是 UTC）。
final baseTime = DateTime(2025, 3, 14, 15, 9, 26);

LegacyTrack legacyTrack({
  required int id,
  String sourceType = 'bilibili',
  String? sourceId,
  String title = 'Synthetic Title',
  String? artist,
  int? durationMs,
  String? thumbnailUrl,
  bool isAvailable = true,
  int? pageCount,
  int? cid,
  int? pageNum,
  String? parentTitle,
  String? originalSongId,
  String? originalSource,
  DateTime? createdAt,
  DateTime? updatedAt,
}) => LegacyTrack(
  id: id,
  sourceId: sourceId ?? 'BV$id',
  sourceType: sourceType,
  title: title,
  artist: artist,
  ownerId: null,
  channelId: null,
  durationMs: durationMs,
  thumbnailUrl: thumbnailUrl,
  isAvailable: isAvailable,
  isVip: false,
  unavailableReason: null,
  playlistInfo: const [],
  pageCount: pageCount,
  cid: cid,
  pageNum: pageNum,
  parentTitle: parentTitle,
  bilibiliAid: null,
  originalSongId: originalSongId,
  originalSource: originalSource,
  createdAt: createdAt ?? baseTime,
  updatedAt: updatedAt,
);

