LegacySnapshot legacySnapshot({
  List<LegacyTrack> tracks = const [],
  List<LegacyPlaylist> playlists = const [],
  LegacyPlayQueue? queue,
  List<LegacyPlayHistory> history = const [],
  LegacySettings? settings,
  List<LegacyRadioStation> radio = const [],
  List<LegacyAccount> accounts = const [],
  int? storedSchemaVersion = 4,
}) => LegacySnapshot(
  tracks: tracks,
  playlists: playlists,
  playQueues: [?queue],
  playHistory: history,
  settings: [settings ?? LegacySettings()],
  searchHistory: const [],
  downloadTasks: const [],
  radioStations: radio,
  lyricsMatches: const [],
  lyricsTitleParseCacheCount: 0,
  accounts: accounts,
  storedSchemaVersion: storedSchemaVersion,
);
